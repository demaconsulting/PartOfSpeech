"""Lexicon coverage check: is the gold tag of a token allowed by the lexicon and the token-shape rules?

  python tools/data/check_lexicon.py [--lexicon data/lexicon/lexicon.tsv]            # check, write coverage.tsv and COVERAGE.md
  python tools/data/check_lexicon.py --sweep [--wordsense-dir DIR]                    # K sweep on train and dev (writes sweep.tsv)

A token is covered when its gold UPOS is in allowed_tags(token, lexicon) (common.py): unknown spellings allow all
17 tags (so they are always covered), known spellings allow their lexicon tags plus the token-shape additions.
Reported per file: all tokens and tokens whose status is not `disputed`, the share of unknown-spelling tokens, and
the misses. Gate G1 (exit code 1 when it fails): at least 99.9% on the non-`disputed` tokens of open train and open dev.
Open test is reported, never gated and never used to choose parameters; every miss on test is listed.
"""
import argparse
import collections
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_lexicon
import common

GATE = 99.9
FILES = (("open/train", "open", "train.tsv"), ("open/dev", "open", "dev.tsv"), ("open/test", "open", "test.tsv"),
         ("masc/masc", "masc", "masc.tsv"))


def tokens_of(path):
    """(form, upos, status) of every non-masked token of a corpus file."""
    for sentence in common.read_corpus(path)[1]:
        for row in sentence["rows"]:
            if row[1] != "_":
                yield row[0], row[1], row[2]


def measure(lexicon, path):
    """Statistics of one file: counts for all tokens (a) and non-disputed tokens (n) and the misses."""
    stats = {"a_tokens": 0, "a_covered": 0, "n_tokens": 0, "n_covered": 0, "unknown": 0}
    misses = collections.defaultdict(lambda: [0, 0])  # (spelling, gold) -> [all, non-disputed]
    for form, upos, status in tokens_of(path):
        disputed = common.parse_status(status)[0] == "disputed"
        covered = upos in common.allowed_tags(form, lexicon)
        if form.lower() not in lexicon:
            stats["unknown"] += 1
        stats["a_tokens"] += 1
        stats["a_covered"] += covered
        if not disputed:
            stats["n_tokens"] += 1
            stats["n_covered"] += covered
        if not covered:
            misses[(form.lower(), upos)][0] += 1
            if not disputed:
                misses[(form.lower(), upos)][1] += 1
    return stats, misses


def pct(part, whole):
    return 100.0 * part / whole if whole else 100.0


def report(lexicon, lexicon_path):
    results = {}
    for name, folder, filename in FILES:
        path = os.path.join(common.DATA, folder, filename)
        if os.path.exists(path):
            results[name] = measure(lexicon, path)
    rows = ["# Coverage of data/lexicon/lexicon.tsv (written by tools/data/check_lexicon.py)",
            "# section summary: summary, file, tokens, covered, percent, nondisputed_tokens, nondisputed_covered, nondisputed_percent, unknown_spelling_tokens",
            "# section miss: miss, file, spelling, gold_tag, tokens, nondisputed_tokens"]
    for name, (stats, _) in results.items():
        rows.append("summary\t%s\t%d\t%d\t%.3f\t%d\t%d\t%.3f\t%d" % (
            name, stats["a_tokens"], stats["a_covered"], pct(stats["a_covered"], stats["a_tokens"]),
            stats["n_tokens"], stats["n_covered"], pct(stats["n_covered"], stats["n_tokens"]), stats["unknown"]))
    for name, (_, misses) in results.items():
        limit = None if name in ("open/dev", "open/test") else 100
        ranked = sorted(misses.items(), key=lambda item: (-item[1][0], item[0]))
        for (spelling, gold), (count, nondisputed) in ranked[:limit]:
            rows.append("miss\t%s\t%s\t%s\t%d\t%d" % (name, spelling, gold, count, nondisputed))
    common.write_text(os.path.join(common.DATA, "lexicon", "coverage.tsv"), rows)
    write_markdown(lexicon, lexicon_path, results)
    return results


def write_markdown(lexicon, lexicon_path, results):
    tags = sum(len(t) for t in lexicon.values())
    lines = [
        "<!-- markdownlint-disable MD013 MD060 -->",
        "",
        "# Lexicon Coverage Report",
        "",
        "Generated by `tools/data/check_lexicon.py` from `data/lexicon/lexicon.tsv`; do not edit by hand.",
        "",
        "The lexicon has %d spellings and %d spelling-tag entries (%.3f tags per spelling on average). A token is "
        "**covered** when its gold tag is allowed by the lexicon and the token-shape rules in `README.md`; "
        "an unknown spelling allows all 17 tags, so it is always covered (the share of unknown-spelling tokens is "
        "reported). `disputed` tokens are the open-corpus tokens on which the two annotators disagreed." % (
            len(lexicon), tags, tags / len(lexicon)),
        "",
        "Gate G1: at least %.1f%% of the non-`disputed` tokens of open train and open dev are covered." % GATE,
        "",
        "## Summary",
        "",
        "| File | Tokens | Covered | All tokens % | Non-disputed tokens | Covered | Non-disputed % | Unknown-spelling tokens |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for name, (stats, _) in results.items():
        lines.append("| `%s` | %d | %d | %.3f | %d | %d | %.3f | %d |" % (
            name, stats["a_tokens"], stats["a_covered"], pct(stats["a_covered"], stats["a_tokens"]),
            stats["n_tokens"], stats["n_covered"], pct(stats["n_covered"], stats["n_tokens"]), stats["unknown"]))
    lines += ["", "Open train is covered by construction when corpus attestation is on (every non-`disputed` "
              "training tag is added to the lexicon); open dev is the gate but its thresholds were tuned on dev, "
              "so open test is the only unbiased report.", ""]
    for name in ("open/dev", "open/test"):
        if name not in results:
            continue
        stats, misses = results[name]
        lines += ["## Misses on `%s`" % name, "",
                  "%d tokens of %d (%d types) have a gold tag that the lexicon does not allow." % (
                      stats["a_tokens"] - stats["a_covered"], stats["a_tokens"], len(misses)), "",
                  "| Spelling | Gold tag | Tokens | Non-disputed tokens | Lexicon tags |", "| --- | --- | ---: | ---: | --- |"]
        for (spelling, gold), (count, nondisputed) in sorted(misses.items(), key=lambda item: (-item[1][0], item[0])):
            lines.append("| `%s` | %s | %d | %d | %s |" % (
                spelling.replace("|", "\\|"), gold, count, nondisputed, " ".join(sorted(lexicon.get(spelling, ())))))
        lines.append("")
    if "masc/masc" in results:
        _, misses = results["masc/masc"]
        lines += ["## Most frequent misses on `masc/masc`", "",
                  "MASC tags are derived from the Penn Treebank by rules and carry mapping noise; the lexicon adds a MASC "
                  "tag only when it occurs at least twice.", "",
                  "| Spelling | Gold tag | Tokens | Lexicon tags |", "| --- | --- | ---: | --- |"]
        for (spelling, gold), (count, _) in sorted(misses.items(), key=lambda item: (-item[1][0], item[0]))[:25]:
            lines.append("| `%s` | %s | %d | %s |" % (
                spelling.replace("|", "\\|"), gold, count, " ".join(sorted(lexicon.get(spelling, ())))))
        lines.append("")
    common.write_text(os.path.join(common.DATA, "lexicon", "COVERAGE.md"), lines[:-1] if lines[-1] == "" else lines)


def sweep(source_dir):
    files = build_lexicon.form_files(source_dir)
    closed = build_lexicon.read_closed_class()
    overrides = build_lexicon.read_overrides()
    train_counts = build_lexicon.attested(os.path.join(common.DATA, "open", "train.tsv"), 1, True)
    masc_counts = build_lexicon.attested(os.path.join(common.DATA, "masc", "masc.tsv"), 1, False)
    rows = ["# K sweep (written by tools/data/check_lexicon.py --sweep): coverage on open train and open dev only (test is never used)",
            "# columns: open_train_k, masc_k, spellings, tags_per_spelling, train_all_pct, train_nondisputed_pct, dev_all_pct, dev_nondisputed_pct"]
    for k, masc_k in ((0, 0), (1, 0), (2, 0), (3, 0), (1, 1), (1, 2), (1, 3), (1, 5), (2, 2)):
        train = {key: v for key, v in train_counts.items() if v >= k}
        masc = {key: v for key, v in masc_counts.items() if v >= masc_k}
        lexicon = build_lexicon.build(files, k, masc_k, closed, overrides, train if k else {}, masc if masc_k else {})
        cells = []
        for filename in ("train.tsv", "dev.tsv"):
            stats, _ = measure(lexicon, os.path.join(common.DATA, "open", filename))
            cells += ["%.3f" % pct(stats["a_covered"], stats["a_tokens"]), "%.3f" % pct(stats["n_covered"], stats["n_tokens"])]
        tags = sum(len(t) for t in lexicon.values())
        row = "%d\t%d\t%d\t%.3f\t%s" % (k, masc_k, len(lexicon), tags / len(lexicon), "\t".join(cells))
        rows.append(row)
        print(row)
    common.write_text(os.path.join(common.DATA, "lexicon", "sweep.tsv"), rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--lexicon", default=os.path.join(common.DATA, "lexicon", "lexicon.tsv"))
    parser.add_argument("--sweep", action="store_true", help="evaluate several attestation thresholds (train and dev only)")
    parser.add_argument("--wordsense-dir", help="local WordSense checkout at the pinned commit (for --sweep)")
    args = parser.parse_args()
    if args.sweep:
        sweep(args.wordsense_dir)
        return
    lexicon = common.read_lexicon(args.lexicon)
    results = report(lexicon, args.lexicon)
    gated = ("open/train", "open/dev")
    failed = False
    for name in gated:
        if name not in results or not results[name][0]["n_tokens"]:
            print("GATE G1 FAILED: no measurement for %s" % name)
            failed = True
    for name, (stats, _) in results.items():
        print("%-10s all %.3f%% (%d/%d)  non-disputed %.3f%% (%d/%d)  unknown-spelling tokens %d" % (
            name, pct(stats["a_covered"], stats["a_tokens"]), stats["a_covered"], stats["a_tokens"],
            pct(stats["n_covered"], stats["n_tokens"]), stats["n_covered"], stats["n_tokens"], stats["unknown"]))
        if name in gated and pct(stats["n_covered"], stats["n_tokens"]) < GATE:
            failed = True
    if failed:
        print("GATE G1 FAILED: non-disputed coverage below %.1f%% on train or dev" % GATE)
        sys.exit(1)
    print("gate G1 passed")


if __name__ == "__main__":
    main()
